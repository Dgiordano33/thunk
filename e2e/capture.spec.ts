import { test, expect } from '@playwright/test';
test('capture bar keeps a dismissed draft and submits a thought', async ({page}) => {
 await page.goto('/inbox');
 await page.getByRole('button',{name:'Relay a thought',exact:true}).click();
 const dialog=page.getByRole('dialog');
 await dialog.getByRole('textbox',{name:'Relay a thought'}).fill('Look into capture browser verification');
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:'Relay a thought',exact:true}).click();
 await expect(dialog.getByRole('textbox')).toHaveValue('Look into capture browser verification');
 await dialog.getByRole('textbox').press('Enter');
 await expect(dialog).not.toBeVisible();
 await expect(page.getByRole('region',{name:'Thoughts'})).toContainText('Look into capture browser verification');
 await expect.poll(async()=>{const r=await page.request.get('/api/captures');return (await r.json()).captures.find((c:{text:string})=>c.text==='Look into capture browser verification')?.status;},{timeout:30000}).toMatch(/working|ready/);
 const rows=await (await page.request.get('/api/captures')).json();
 const id=rows.captures.find((c:{text:string})=>c.text==='Look into capture browser verification').id;
 expect((await page.request.post(`/api/captures/${id}/discard`,{data:{}})).ok()).toBeTruthy();
 await expect.poll(async()=> (await (await page.request.get('/api/captures')).json()).captures.some((c:{id:string})=>c.id===id)).toBe(false);
 expect((await page.request.post(`/api/captures/${id}/restore`,{data:{}})).ok()).toBeTruthy();
 await expect.poll(async()=> (await (await page.request.get('/api/captures')).json()).captures.some((c:{id:string})=>c.id===id)).toBe(true);
});
