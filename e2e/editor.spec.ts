import { test, expect } from '@playwright/test';
import { newBoard, seed, openCanvas, card } from './canvas';

test('rich document editing survives reload and supports slash, table, toggle and color controls', async ({ page, request }) => {
  const board = await newBoard(request);
  const [c] = seed(board, [{ x: 40, y: 50, width: 900, title: 'Editing', markdown: 'Pricing overview' }]);
  const { errors } = await openCanvas(page, board, 1);
  const root = card(page, c.id), editor = root.locator('.tiptap');
  await editor.click(); await page.keyboard.press('End'); await page.keyboard.press('Enter'); await page.keyboard.type('/table');
  await expect(page.getByRole('listbox', { name: 'Insert block' })).toBeVisible();
  await page.keyboard.press('Enter');
  await expect(root.locator('table')).toHaveCount(1);
  await page.keyboard.type('Hobby');
  await root.getByRole('button', { name: 'Table actions', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Column after', exact: true }).click();
  await expect(root.locator('tr').first().locator('th')).toHaveCount(4);
  await root.getByRole('button', { name: 'Block', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Move up', exact: true }).click();
  await expect.poll(async () => (await (await request.get(board.api)).json()).cards.find((x: {id:string}) => x.id === c.id).markdown, { timeout: 30000 }).toMatch(/^\| Hobby /m);
  await page.reload(); await expect(card(page, c.id).locator('table')).toContainText('Hobby');
  await card(page, c.id).locator('.tiptap > p').last().click();
  await card(page, c.id).getByRole('button', { name: 'Insert / Turn into', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Toggle', exact: true }).click();
  await expect(card(page, c.id).locator('details')).toHaveCount(1);
  await card(page, c.id).getByRole('button', { name: 'Toggle title', exact: true }).click();
  await page.getByRole('textbox', { name: 'Toggle title title', exact: true }).fill('Pricing details');
  await page.getByRole('button', { name: 'Apply', exact: true }).click();
  await expect(card(page, c.id).locator('summary')).toHaveText('Pricing details');
  await card(page, c.id).locator('summary').click();
  await expect(card(page, c.id).locator('details')).not.toHaveAttribute('open');
  await page.screenshot({ path: '.context/document-editing.png' });
  expect(errors).toEqual([]);
});

for (const look of ['vanilla', 'space']) test(`${look}: colors, callouts, media, references and contents render after saving`, async ({ page, context, request }) => {
  await context.addCookies([{ name: 'thunk.look', value: look, url: 'http://127.0.0.1:4517' }]);
  const board = await newBoard(request);
  const [c] = seed(board, [{ x: 30, y: 30, width: 850, title: 'Rich content', markdown: '# Overview\n\nColor me' }]);
  const { errors } = await openCanvas(page, board, 1);
  const root = card(page, c.id);
  await root.locator('.tiptap > p').last().click(); await page.keyboard.press('Home'); await page.keyboard.press('Shift+End');
  await root.getByRole('button', { name: 'Format', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Text: important', exact: true }).click();
  await expect(root.locator('[data-ink="important"]')).toHaveText('Color me');
  await root.getByRole('button', { name: 'Insert / Turn into', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Callout', exact: true }).click();
  await expect(root.locator('.editor-callout')).toContainText('Color me');
  await root.locator('.editor-callout p').click();
  await page.keyboard.press('End');
  await root.getByRole('button', { name: 'Insert / Turn into', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Reference', exact: true }).click();
  await root.getByRole('button', { name: 'Overview', exact: true }).click();
  await expect(root.locator('.tiptap a')).toHaveAttribute('href', /^#block-/);
  await root.getByRole('button', { name: 'Insert / Turn into', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Table of contents', exact: true }).click();
  await expect(root.getByRole('navigation', { name: 'Table of contents' })).toContainText('Overview');
  await root.getByRole('button', { name: 'Insert / Turn into', exact: true }).click();
  await page.getByRole('menuitem', { name: 'File', exact: true }).click();
  await root.getByRole('textbox', { name: 'File URL' }).fill('https://example.com/report.pdf');
  await root.getByRole('textbox', { name: 'File title' }).fill('Pricing report');
  await root.getByRole('button', { name: 'Apply', exact: true }).click();
  await expect(root.getByRole('link', { name: 'Pricing report' })).toHaveAttribute('href', 'https://example.com/report.pdf');
  await expect.poll(async () => (await (await request.get(board.api)).json()).cards.find((x: {id:string}) => x.id === c.id).markdown, { timeout: 30000 }).toContain('Pricing report');
  await page.reload();
  await expect(card(page, c.id).locator('.editor-callout')).toContainText('Color me');
  await expect(card(page, c.id).getByRole('link', { name: 'Pricing report' })).toBeVisible();
  await expect(card(page, c.id).getByRole('navigation', { name: 'Table of contents' })).toContainText('Overview');
  await page.screenshot({ path: `.context/document-editing-${look}.png` });
  expect(errors).toEqual([]);
});
