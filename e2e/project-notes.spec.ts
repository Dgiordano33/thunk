import { expect, test } from '@playwright/test';
import path from 'node:path';

test('notes belong to projects, can link and unlink, and survive workspace removal', async ({ page, request, context, baseURL }) => {
  await context.addCookies([{ name: 'thunk.onboarding', value: 'intro,checklist-dismissed,map-legend', url: baseURL! }]);
  const created = await request.post('/api/projects', { data: { name: `Project notes ${Date.now()}`, repos: [] } });
  expect(created.ok()).toBeTruthy();
  const { project } = await created.json();
  const ws = await request.post('/api/workspaces', { data: { projectId: project.id, name: 'Berlin' } });
  expect(ws.ok()).toBeTruthy();
  const { workspace } = await ws.json();
  const result = await request.post(`/api/projects/${project.id}/notes`, { data: { title: 'Launch plan', markdown: 'Keep this plan after the workspace closes.' } });
  expect(result.ok()).toBeTruthy();
  const { note } = await result.json();
  await page.goto(`/notes?scope=p:${project.id}&note=${note.id}`);
  const link = page.getByRole('button', { name: 'Link note to workspaces' });
  await expect(link).toBeVisible();
  await link.click();
  await page.getByRole('menuitemcheckbox', { name: 'Berlin', exact: true }).click();
  await expect.poll(async () => (await (await request.get(`/api/workspaces/${workspace.id}/notes`)).json()).notes.map((n: { id: string }) => n.id)).toEqual([note.id]);
  await expect(link).toHaveText('1 workspace');
  await link.click();
  await page.getByRole('menuitemcheckbox', { name: 'Berlin', exact: true }).click();
  await expect.poll(async () => (await (await request.get(`/api/workspaces/${workspace.id}/notes`)).json()).notes).toEqual([]);
  expect((await request.get(`/api/projects/${project.id}/notes/${note.id}`)).ok()).toBeTruthy();
  await link.click();
  await page.getByRole('menuitemcheckbox', { name: 'Berlin', exact: true }).click();
  await expect(link).toHaveText('1 workspace');
  await page.screenshot({ path: path.join(process.cwd(), '.context/project-notes.png'), fullPage: true });
  expect((await request.patch(`/api/workspaces/${workspace.id}`, { data: { status: 'archived' } })).ok()).toBeTruthy();
  expect((await request.delete(`/api/workspaces/${workspace.id}`)).ok()).toBeTruthy();
  const saved = await request.get(`/api/projects/${project.id}/notes/${note.id}`);
  expect(saved.ok()).toBeTruthy();
  expect((await saved.json()).note.markdown).toContain('Keep this plan');
  await page.reload();
  await expect(link).toBeVisible();
  await link.click();
  await page.getByRole('menuitemcheckbox', { name: 'Closed workspace' }).click();
  await expect(link).toHaveText('Link workspace');
});
